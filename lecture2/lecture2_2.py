# summing up values
total = 176 + 287
print(total)

# substraction example
difference = 1856 - 917
print(difference)

# we typically use variables in calculations
# instead of just numeric values
salary = 2700

# basically => change salary to be a new value
# in this case: NEW SALARY value => OLD SALARY * 1.2
# NOTE! this code adds +20% to old salary
# easiest way => multiply by 1.2
salary = salary * 1.2
print(salary)

# typical division
wind_speed = 25 / 3.6
print(wind_speed)

# you can use // to remove the decimals
apples = 25 // 4
print(apples)

# remainder (modulus) is the opposite of //
# ==> %
# the reasoning: 4 * 6 = 24
# 25 - 24 => 1
leftover = 25 % 4
print(leftover)

# this is a shortcut for:
# salary = salary + 450

# however, this shortcut style is VERY common!
salary += 450
print(salary)